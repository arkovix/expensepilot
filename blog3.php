            <h2>Common Mistakes Beginners Make When Tracking Expenses</h2>
            <img src="asset/mistake.png" width="300px" height="150px" class="im"  alt="mistakimage">
            <p class="text">Even with the right system, people fall into a few traps early on. Watch out for these:</p>
            <p class="text"><b>1. Waiting to record at the end of the week.</b>By then, you've already forgotten half your transactions. Record daily — even if it's just 5 minutes at night.<br><br><b>2. Skipping cash transactions.</b> UPI and card payments leave a digital trail. Cash doesn't. Many people track their digital spending perfectly and have no idea what happened to their cash. Treat cash like any other payment — log it immediately.<br><br><b>3. Creating too many categories.</b>
            "Street food," "restaurant food," "home food," "café food" — just use one: Food. Over-categorizing makes the system feel complicated, and you'll abandon it.<br><br><b>4. Being too hard on yourself after overspending.</b>
            One bad week doesn't break the system. Review it, understand it, and move on. Consistency over perfection is what builds the habit.<br><br><b>5. Tracking for a few days and stopping.</b> 
            Expense tracking only becomes useful after 3–4 weeks, when patterns start to emerge. Push through the first month even if it feels pointless — it isn't.</p>



            <h2>The Real Benefits of Tracking Your Daily Expenses</h2>
            <p class="text">Here's what consistently tracking your expenses actually does over time:</p>
            <ul class="list">
                <li class="lili">You stop leaking money on small, forgettable purchases that add up to thousands a month</li>
                <li class="lili">You make better decisions because you can see the real cost of habits (like daily food delivery)</li>
                <li class="lili">You hit savings goals faster because you know exactly how much is available each month</li>
                <li class="lili">You feel less anxious about money because uncertainty disappears — you always know where you stand</li>
                <li class="lili">You build a financial baseline that makes planning for the future (EMIs, a trip, an emergency) actually possible</li>
            </ul>
            <p class="text">The students and young professionals who start tracking early consistently report that it's one of the best money habits they've ever built — not because it's exciting, but because it works.</p>

