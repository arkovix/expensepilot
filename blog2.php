            <h2>Common Money Mistakes Students Make (And How to Avoid Them)</h2>
            <img src="asset/mistake.png" width="300px" height="150px" class="im"  alt="mistakimage">
            <p class="text">Event with good intentions, stidents fall into predictable traps. Here are the most common ones:</p>
            <p class="text"><b>1. Spending first, saving later.</b>Whatever is left at the end of the month almost never gets saved. Save a fixed amount on Day 1, before you spend anything else.<br><br><b>2. Using UPI without tracking.</b> Paying ₹50 here and ₹120 there via UPI feels almost weightless. But those transactions add up fast. Check your UPI statement every Sunday — you'll be surprised.<br><br><b>3. Ignoring small subscriptions.</b>That ₹99/month OTT plan, the ₹49 gaming subscription, the ₹149 cloud storage — these are nearly invisible. List all recurring subscriptions and cancel what you don't actively use.<br><br><b>4. No emergency fund.</b>Something unexpected will happen — a medical expense, a broken phone screen, an unplanned trip home. Students without an emergency fund end up borrowing or going without. Even ₹300–₹500/month builds a buffer over time.<br><br><b>5. Comparing with peers.</b> Your friend splurging on a ₹800 restaurant dinner doesn't mean you should too. Everyone's financial situation is different. Your budget is yours — protect it.</p>



            <h2>Smart Money-Saving Hacks That Actually Work in India</h2>
            <p class="text">These aren't vague tips. These are things that real students use:<br><br><b>Cook at least 4–5 days a week.</b> Even basic dal-rice cooked in a hostel room saves ₹500–₹1,000 compared to ordering food daily.<br><b>Use student discounts aggressively.</b>Platforms like Spotify, Amazon Prime, and many SaaS tools offer student plans at 50–70% off. Always ask.<br><b>Walk or cycle for short distances.</b> Saves money and keeps you healthy — a win on both ends.<br><b>Buy second-hand textbooks.</b> Use college Facebook groups, seniors, or platforms like OLX. You can save hundreds per semester.<br><b>Set a "cooling off" rule for non-essential purchases.</b> If you want to buy something that costs more than ₹300, wait 24 hours. You'll often find you didn't want it that badly.<br><b>Use cashback apps and UPI offers.</b> Google Pay, PhonePe, and Paytm regularly offer cashback on transactions. This isn't much individually, but it adds up to a few hundred rupees per month.</p><br>
            
